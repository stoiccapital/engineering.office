/**
 * Compute HOAI fee by linear interpolation per §13.
 * Returns null if kosten is outside the Honorartafel range (fee is "frei vereinbar").
 */
export function computeHonorar(
  lb: Leistungsbild,
  anrechenbareKosten: number,
  zone: Zone,
  satz: Honorarsatz
): { netto: number | null; von: number; bis: number; outOfRange: boolean } {
  if (anrechenbareKosten < lb.min || anrechenbareKosten > lb.max) {
    return { netto: null, von: 0, bis: 0, outOfRange: true };
  }
  const zIdx = lb.zones.indexOf(zone);
  if (zIdx < 0) {
    return { netto: null, von: 0, bis: 0, outOfRange: true };
  }
  const vonCol = zIdx * 2;
  const bisCol = zIdx * 2 + 1;

  // Find bracketing rows
  let lower = lb.table[0];
  let upper = lb.table[lb.table.length - 1];
  for (let i = 0; i < lb.table.length - 1; i++) {
    const [k1] = lb.table[i];
    const [k2] = lb.table[i + 1];
    if (anrechenbareKosten >= k1 && anrechenbareKosten <= k2) {
      lower = lb.table[i];
      upper = lb.table[i + 1];
      break;
    }
  }

  const [k1, v1] = lower;
  const [k2, v2] = upper;
  const t = k2 === k1 ? 0 : (anrechenbareKosten - k1) / (k2 - k1);

  const vonLow = v1[vonCol], vonHigh = v2[vonCol];
  const bisLow = v1[bisCol], bisHigh = v2[bisCol];
  const von = vonLow + (vonHigh - vonLow) * t;
  const bis = bisLow + (bisHigh - bisLow) * t;

  let netto: number;
  if (satz === "basis") netto = von;
  else if (satz === "oberer") netto = bis;
  else netto = (von + bis) / 2;

  return { netto, von, bis, outOfRange: false };
}
